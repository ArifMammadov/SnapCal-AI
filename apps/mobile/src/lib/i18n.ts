const STORAGE_KEY = 'snapcal_language'

export const SUPPORTED_LANGUAGES: Language[] = ['en', 'ru', 'uz', 'kk', 'az', 'tr', 'ar']

let currentLanguage: Language = 'en'

export function getCurrentLanguage(): Language {
  return currentLanguage
}

export function setCurrentLanguage(lang: Language) {
  currentLanguage = lang
  if (typeof window !== 'undefined') {
    localStorage.setItem(STORAGE_KEY, lang)
  }
}

export function getStoredLanguage(): Language | null {
  if (typeof window === 'undefined') return null
  const stored = localStorage.getItem(STORAGE_KEY)
  if (stored && SUPPORTED_LANGUAGES.includes(stored as Language)) return stored as Language
  return null
}

export function detectLanguage(): Language {
  if (typeof window !== 'undefined') {
    const stored = getStoredLanguage()
    if (stored) return stored
    const tgUser = window.Telegram?.WebApp?.initDataUnsafe?.user
    const tgCode = tgUser?.language_code
    if (tgCode) {
      const code = tgCode.toLowerCase().split('-')[0]
      if (SUPPORTED_LANGUAGES.includes(code as Language)) return code as Language
      if (['ru', 'uk', 'be'].includes(code)) return 'ru'
    }
    const regionCode = (tgUser as any)?.region?.toUpperCase?.() || ''
    if (regionCode === 'UZ') return 'uz'
    if (regionCode === 'KZ') return 'kk'
    if (regionCode === 'AZ') return 'az'
    if (regionCode === 'TR') return 'tr'
    if (['SA','AE','QA','KW','BH','OM','EG','MA','DZ','TN'].includes(regionCode)) return 'ar'
    const browserLang = navigator.language || (navigator as any).userLanguage
    const browserCode = browserLang?.toLowerCase().split('-')[0]
    if (SUPPORTED_LANGUAGES.includes(browserCode as Language)) return browserCode as Language
    if (['ru', 'uk', 'be'].includes(browserCode ?? '')) return 'ru'
  }
  return 'en'
}

export function initLanguage(): Language {
  const lang = detectLanguage()
  currentLanguage = lang
  setCurrentLanguage(lang)
  return lang
}

export function t(key: TranslationKey, ...args: any[]): string {
  const dict: Record<Language, Record<TranslationKey, string | ((...args: any[]) => string)>> = { en, ru, uz, kk, az, tr, ar }
  const dictLang = dict[currentLanguage] ?? en
  let value = dictLang[key]
  if (value === undefined || value === null || value === '') {
    value = en[key]
  }
  if (typeof value === 'function') {
    return (value as (...args: any[]) => string)(...args)
  }
  if (typeof value === 'string') return value
  return key
}

